"""Score pre-built benchmark artifacts with the same sandbox harness.

Use this when the artifacts were produced outside the LM Studio client
(for example, generated by the agent itself). Each task runs with
max_repair_attempts=0 so the score reflects the first (only) output.
"""

from __future__ import annotations

import argparse
import time
from dataclasses import replace
from datetime import datetime
from pathlib import Path

from lm_optimizer.services.sandbox_history import record_run
from lm_optimizer.services.sandbox_lab import SANDBOX_TASKS, SandboxPolicy
from lm_optimizer.services.sandbox_runner import SandboxRunner, build_command_for

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "benchmarks" / "deepseek_agent"
OUT = ROOT / "results" / "bakeoff" / "deepseek-agent"
MODEL = "deepseek-v4.1-flash (agent)"

TASKS = {
    "minecraft_world": "index.html",
    "web_dashboard": "index.html",
    "email_write": "email.txt",
    "blender_skyblock": "build_scene.py",
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--tasks",
        default="all",
        help="comma-separated task ids, or 'all'",
    )
    args = parser.parse_args()
    selected = (
        list(TASKS)
        if args.tasks.strip().lower() in ("all", "*")
        else [t.strip() for t in args.tasks.split(",") if t.strip()]
    )
    unknown = [t for t in selected if t not in TASKS]
    if unknown:
        print(f"unknown task(s): {', '.join(unknown)}")
        return 2
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    rows = []
    for task_id in selected:
        filename = TASKS[task_id]
        definition = SANDBOX_TASKS[task_id]
        definition = replace(definition, max_repair_attempts=0)
        source = SOURCE / task_id / filename
        if not source.exists():
            print(f"[skip] {task_id}: missing {source}")
            continue
        content = source.read_text(encoding="utf-8")
        workdir = OUT / task_id / stamp
        policy = SandboxPolicy(
            workdir=workdir,
            network_enabled=False,
            timeout_s=definition.timeout_s,
            allowed_executables=definition.allowed_executables,
        )
        runner = SandboxRunner(
            task=definition,
            policy=policy,
            workdir=workdir,
            command=build_command_for(definition),
        )
        started = time.perf_counter()
        result = runner.run(lambda feedback: content)
        wall_s = time.perf_counter() - started
        payload = result.as_dict()
        record_run(MODEL, task_id, payload, workdir=str(workdir), duration_s=wall_s)
        row = {
            "task": task_id,
            "score": payload["final_score"],
            "pass": payload["final_success"],
            "error": payload["error"],
            "wall_s": round(wall_s, 1),
            "artifacts": payload["artifacts"],
            "workdir": str(workdir),
        }
        rows.append(row)
        print(
            f"[{task_id}] score={row['score']} pass={row['pass']} "
            f"wall={row['wall_s']}s artifacts={row['artifacts']} "
            f"error={row['error'][:120]}"
        )
    return 0 if rows else 2


if __name__ == "__main__":
    raise SystemExit(main())
