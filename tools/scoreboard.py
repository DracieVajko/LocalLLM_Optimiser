"""Build SCOREBOARD.md from measured runs and rendered screenshots.

Two rules keep the table honest:

* a run whose model produced no text, or crashed the server, is *not measured*
  and never contributes a 0.00 to a mean;
* a web/3D score is accompanied by the pixel verdict of its screenshot, so a
  blank canvas cannot look like a pass.

Usage:
    python tools/scoreboard.py
    python tools/scoreboard.py --out SCOREBOARD.md
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from lm_optimizer.services.png_stats import measure_png  # noqa: E402
from lm_optimizer.services.sandbox_history import origin_of  # noqa: E402

RUNS = ROOT / "results" / "bakeoff" / "runs.jsonl"
VISUALS = ROOT / "results" / "compare" / "visuals"
HISTORY = ROOT / "results" / "sandbox_runs.jsonl"

TEXT_TASKS = (
    "email_write",
    "calendar_event",
    "deep_research",
    "research_synthesis",
    "web_fetch_brief",
    "web_search",
)
VISUAL_TASKS = (
    "minecraft_world",
    "company_website",
    "deep_research_report",
    "blender_city",
)


def _load_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        try:
            rows.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return rows


def measured(row: dict) -> bool:
    """A run counts only when the model actually produced output."""
    if str(row.get("status") or "measured") != "measured":
        return False
    if row.get("final_score") is None:
        return False
    # Legacy rows predate the status field: a 0.00 after <1 s is a non-run.
    if row.get("final_score") == 0.0 and float(row.get("gen_s") or 0) < 1.0:
        return False
    return True


def latest(runs: list[dict]) -> dict[tuple[str, str], dict]:
    newest: dict[tuple[str, str], dict] = {}
    for row in runs:
        key = (str(row.get("model")), str(row.get("task")))
        newest[key] = row
    return newest


def text_table(rows: list[dict]) -> list[str]:
    by_model: dict[str, dict[str, float]] = {}
    for row in rows:
        task = str(row.get("task"))
        if task not in TEXT_TASKS or not measured(row):
            continue
        by_model.setdefault(str(row.get("model")), {})[task] = float(row["final_score"])

    lines = [
        "| model | " + " | ".join(TEXT_TASKS) + " | Tier-A | n |",
        "|---|" + "---:|" * (len(TEXT_TASKS) + 2),
    ]
    ranked = sorted(
        by_model.items(),
        key=lambda item: -statistics.fmean(item[1].values()),
    )
    for model, scores in ranked:
        cells = [f"{scores[t]:.2f}" if t in scores else "-" for t in TEXT_TASKS]
        mean = statistics.fmean(scores.values())
        lines.append(
            f"| {model} | " + " | ".join(cells) + f" | **{mean:.2f}** | {len(scores)}/{len(TEXT_TASKS)} |"
        )
    return lines


def pixel_rows() -> list[dict]:
    if not VISUALS.exists():
        return []
    rows = []
    for image in sorted(VISUALS.glob("*.png")):
        task = next(
            (t for t in sorted(VISUAL_TASKS, key=len, reverse=True) if image.stem.endswith(t)),
            "",
        )
        provider = image.stem[: -(len(task) + 1)] if task else image.stem
        stats = measure_png(image)
        rows.append(
            {
                "provider": provider,
                "task": task or "?",
                "mean": stats.mean,
                "sd": stats.sd,
                "dark": stats.dark_pct,
                "tones": stats.tones,
                "verdict": stats.verdict,
                "file": image.name,
            }
        )
    return rows


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=str(ROOT / "results" / "scoreboard.md"))
    args = parser.parse_args()

    runs = list(latest(_load_jsonl(RUNS)).values()) + _load_jsonl(HISTORY)
    local = [row for row in runs if origin_of(row) != "frontier"]
    frontier = [row for row in runs if origin_of(row) == "frontier"]
    clean = [row for row in local if measured(row)]
    rejected = len(local) - len(clean)

    lines = [
        "# Scoreboard",
        "",
        "Generated by `python tools/scoreboard.py` from `results/`.",
        "",
        f"- measured runs: **{len(clean)}**",
        f"- excluded (no output, crash, or legacy sub-second 0.00): **{rejected}**",
        f"- frontier (API) runs kept out of the local table: **{sum(1 for r in frontier if measured(r))}**",
        "",
        "Only text tasks with deterministic checks are ranked. Visual tasks get a",
        "pixel verdict instead, because their score cannot see the canvas.",
        "",
        "## Text tasks (measured runs only)",
        "",
    ]
    lines += text_table(clean)
    lines += [
        "",
        "## Rendered artifacts (pixel verdict)",
        "",
        "| provider | task | mean | sd | dark | tones | verdict |",
        "|---|---|---:|---:|---:|---:|---|",
    ]
    for row in pixel_rows():
        lines.append(
            f"| {row['provider']} | {row['task']} | {row['mean']:.1f} | {row['sd']:.1f} | "
            f"{row['dark']:.0f}% | {row['tones']} | **{row['verdict']}** |"
        )

    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
