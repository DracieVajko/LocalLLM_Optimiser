"""Regenerate the model bake-off comparison report from results/bakeoff/runs.jsonl.

Produces (next to this tool):
  - comparison.md   human-readable markdown table
  - comparison.csv  opens directly in Excel

Run after every finished model:
    python tools/bakeoff_report.py
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "results" / "bakeoff" / "runs.jsonl"
OUT_MD = ROOT / "comparison.md"
OUT_CSV = ROOT / "comparison.csv"

COLUMNS = [
    "model",
    "task",
    "score",
    "pass",
    "repair",
    "load_s",
    "gen_s",
    "total_s",
    "tokens",
    "tok_s",
    "thinking_chars",
    "context",
    "error",
]


def _rows() -> list[dict]:
    if not RUNS.exists():
        return []
    rows: list[dict] = []
    for line in RUNS.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            rows.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    # Keep the latest record per (model, task); append-only history can contain
    # failed retries of the same run. The latest row is the current status.
    deduped: dict[tuple[str, str], dict] = {}
    for row in rows:
        deduped[(str(row.get("model", "")), str(row.get("task", "")))] = row
    rows = list(deduped.values())
    # Agent-generated artifacts are scored by the sandbox harness, so their
    # records live in sandbox_runs.jsonl. Merge them with load/gen semantics
    # that make clear no LM Studio load happened.
    sandbox_runs = ROOT / "results" / "sandbox_runs.jsonl"
    if sandbox_runs.exists():
        latest_agent: dict[str, dict] = {}
        for line in sandbox_runs.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                continue
            if r.get("model") != "deepseek-v4.1-flash (agent)":
                continue
            # Later records win: one row per task, the latest attempt.
            latest_agent[r.get("task")] = r
        for r in latest_agent.values():
            rows.append(
                {
                    "model": r.get("model"),
                    "task": r.get("task"),
                    "final_score": r.get("final_score"),
                    "final_success": r.get("final_success"),
                    "repair_count": r.get("repair_count", 0),
                    "load_s": 0,
                    "gen_s": r.get("duration_s", 0),
                    "total_s": r.get("duration_s", 0),
                    "tokens": None,
                    "tok_s": None,
                    "thinking_chars": None,
                    "context": 0,
                    "error": r.get("error", ""),
                }
            )
    return rows


def _fmt(x) -> str:
    if x is None or x == "":
        return "-"
    if isinstance(x, float):
        return f"{x:g}"
    return str(x)


def write_markdown(rows: list[dict], path: Path, frontier_only: bool = False) -> None:
    by_model: dict[str, list[dict]] = {}
    for r in rows:
        by_model.setdefault(r.get("model", "(unknown)"), []).append(r)

    lines: list[str] = []
    lines.append("# Model bake-off comparison")
    lines.append("")
    lines.append("Generated from `results/bakeoff/runs.jsonl` plus agent rows from `results/sandbox_runs.jsonl`. Generation time includes the model's thinking phase where supported.")
    lines.append("")
    lines.append("Agent rows (`deepseek-v4.1-flash (agent)`) are artifacts generated by the agent and scored by the same harness; their time is wall-clock and there is no model load or server token stats.")
    lines.append("")

    # Per-model totals
    lines.append("## Model totals (load once + all tasks)")
    lines.append("")
    lines.append(
        "| model | mean score | tasks passed | load_s | total gen_s | total_s | tokens | tok/s | thinking_chars |"
    )
    lines.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    order = list(by_model.keys())
    for model in order:
        model_rows = [r for r in by_model[model] if r.get("task") != "(load)" and r.get("task") != "(crash)"]
        load_s = next((r.get("load_s") or 0 for r in by_model[model]), 0)
        gen_s = round(sum(float(r.get("gen_s") or 0) for r in model_rows), 1)
        total_s = round(load_s + gen_s, 1)
        tokens = sum(int(r.get("tokens") or 0) for r in model_rows)
        toks = round(tokens / gen_s, 2) if gen_s else 0.0
        thinking = sum(int(r.get("thinking_chars") or 0) for r in model_rows)
        scores = [float(r["final_score"]) for r in model_rows if r.get("final_score") is not None]
        mean = round(sum(scores) / len(scores), 3) if scores else 0.0
        passed = sum(1 for r in model_rows if r.get("final_success"))
        lines.append(
            f"| {model} | {mean} | {passed}/{len(model_rows)} | {load_s} | {gen_s} | {total_s} | "
            f"{tokens} | {toks} | {thinking} |"
        )
    lines.append("")

    # Per-task detail
    lines.append("## Per-task detail")
    lines.append("")
    lines.append(
        "| model | task | score | pass | repair | load_s | gen_s | total_s | tokens | tok/s | thinking_chars | context | error |"
    )
    lines.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for model in order:
        for r in sorted(by_model[model], key=lambda x: x.get("task", "")):
            task = r.get("task", "(unknown)")
            if task in ("(load)", "(crash)"):
                continue
            lines.append(
                f"| {model} | {task} | {_fmt(r.get('final_score'))} | "
                f"{_fmt(r.get('final_success'))} | {_fmt(r.get('repair_count'))} | "
                f"{_fmt(r.get('load_s'))} | {_fmt(r.get('gen_s'))} | {_fmt(r.get('total_s'))} | "
                f"{_fmt(r.get('tokens'))} | {_fmt(r.get('tok_s'))} | {_fmt(r.get('thinking_chars'))} | "
                f"{_fmt(r.get('context'))} | {_fmt(r.get('error'))[:80]} |"
            )
    lines.append("")

    # KV cache A/B block (local models only).
    cache_files: list[str] = []
    if not frontier_only:
        cache_path = ROOT / "results" / "bakeoff" / "cache_ab_*.json"
        import glob as _glob
        cache_files = sorted(_glob.glob(str(cache_path)))
    if cache_files:
        latest = cache_files[-1]
        try:
            data = json.loads(Path(latest).read_text(encoding="utf-8"))
            variants = data.get("variants", [])
            if variants:
                lines.append("## KV cache placement (same weights, context 8192)")
                lines.append("")
                lines.append("| model | context | KV_GPU load_s | KV_RAM load_s | KV_GPU tok/s | KV_RAM tok/s | faster |")
                lines.append("|---|---|---:|---:|---:|---:|---|")
                model_name = data.get("model", "(unknown)")
                context = data.get("context", "-")
                v_by = {v["kv_gpu"]: v for v in variants}
                vgpu = v_by.get(True, {})
                vram = v_by.get(False, {})
                runs_g = vgpu.get("runs", [])
                runs_r = vram.get("runs", [])
                def avg(runs: list[dict], key: str) -> float:
                    vals = [float(x.get(key) or 0) for x in runs if x.get(key) is not None]
                    return round(sum(vals) / len(vals), 2) if vals else 0.0
                load_g = vgpu.get("load_s", "-")
                load_r = vram.get("load_s", "-")
                tok_g = avg(runs_g, "tok_s")
                tok_r = avg(runs_r, "tok_s")
                faster = "GPU" if tok_g >= tok_r else "RAM"
                lines.append(
                    f"| {model_name} | {context} | {load_g} | {load_r} | {tok_g} | {tok_r} | {faster} |"
                )
                lines.append("")
        except (json.JSONDecodeError, OSError):
            pass

    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_csv(rows: list[dict], path: Path) -> None:
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=COLUMNS, extrasaction="ignore")
        writer.writeheader()
        for r in rows:
            task = r.get("task", "(unknown)")
            if task in ("(load)", "(crash)"):
                continue
            writer.writerow(
                {
                    "model": r.get("model", ""),
                    "task": task,
                    "score": r.get("final_score", ""),
                    "pass": r.get("final_success", ""),
                    "repair": r.get("repair_count", ""),
                    "load_s": r.get("load_s", ""),
                    "gen_s": r.get("gen_s", ""),
                    "total_s": r.get("total_s", ""),
                    "tokens": r.get("tokens", ""),
                    "tok_s": r.get("tok_s", ""),
                    "thinking_chars": r.get("thinking_chars", ""),
                    "context": r.get("context", ""),
                    "error": r.get("error", ""),
                }
            )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--frontier-only",
        action="store_true",
        help="keep only agent/frontier rows (no local model results)",
    )
    parser.add_argument(
        "--out-dir",
        default="",
        help="write frontier_comparison.md/csv into this directory",
    )
    args = parser.parse_args()

    rows = _rows()
    if args.frontier_only:
        rows = [
            r for r in rows
            if "agent" in str(r.get("model", "")).lower()
        ]
    out_md, out_csv = OUT_MD, OUT_CSV
    if args.out_dir:
        out = Path(args.out_dir)
        out.mkdir(parents=True, exist_ok=True)
        out_md = out / "frontier_comparison.md"
        out_csv = out / "frontier_comparison.csv"
    write_markdown(rows, out_md, frontier_only=args.frontier_only)
    write_csv(rows, out_csv)
    print(f"wrote {out_md}  ({len(rows)} raw records)")
    print(f"wrote {out_csv}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
